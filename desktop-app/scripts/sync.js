// Builds src/overlay.html from the browser demo (../cursor-puppy.html): same pet, same code,
// with the Google Fonts link swapped for the bundled font files so it works offline.
const fs = require('fs');
const path = require('path');

const demo = path.join(__dirname, '..', '..', 'cursor-puppy.html');
const out = path.join(__dirname, '..', 'src', 'overlay.html');
if (!fs.existsSync(demo)) { console.log('sync: demo not found, keeping existing overlay.html'); process.exit(0); }

let html = fs.readFileSync(demo, 'utf8');
const fonts = `<style>
@font-face { font-family: 'Baloo 2'; font-weight: 600; src: url('fonts/baloo-2-latin-600-normal.woff2') format('woff2'); }
@font-face { font-family: 'Baloo 2'; font-weight: 800; src: url('fonts/baloo-2-latin-800-normal.woff2') format('woff2'); }
</style>`;
html = html.replace(/<!--FONTS-->[\s\S]*?<!--\/FONTS-->/, fonts);
html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'unsafe-inline'; font-src 'self'">
<!-- Generated by scripts/sync.js from cursor-puppy.html. Edit the demo, then run npm run sync. -->
${html.replace('</style>\n\n<div id="world">', '</style>\n</head>\n<body>\n<div id="world">')}
</body>
</html>
`;
fs.writeFileSync(out, html);
console.log('sync: wrote', path.relative(process.cwd(), out));
